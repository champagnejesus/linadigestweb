begin;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  sku text not null unique,
  barcode text unique,
  stock integer not null default 0 check (stock >= 0),
  cost integer not null,
  price integer not null,
  min_stock integer not null default 300,
  unit text not null default 'unidad',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  type text not null check (type in ('initial', 'entry', 'output')),
  quantity integer not null check (quantity > 0),
  delta integer not null,
  reason text not null,
  lot text,
  expiration_date date,
  note text,
  source text not null default 'manual' check (source in ('manual', 'scanner')),
  reference text unique,
  user_id text not null,
  user_name text not null,
  created_at timestamptz not null default now()
);

create index if not exists movements_product_created_idx
  on public.movements(product_id, created_at desc, id desc);

create table if not exists public.label_prints (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  label_size text not null check (label_size in ('standard', 'compact')),
  printed_by_user_id text not null,
  printed_by_user_name text not null,
  printed_at timestamptz not null default now(),
  used_at timestamptz,
  used_by_user_id text,
  used_movement_reference text unique
);

create index if not exists label_prints_product_created_idx
  on public.label_prints(product_id, printed_at desc, id desc);

create table if not exists public.app_users_v2 (
  id bigint generated by default as identity primary key,
  name text not null,
  email text unique,
  username text unique,
  password_hash text,
  password_salt text,
  must_change_password boolean not null default true,
  failed_login_attempts integer not null default 0,
  locked_until timestamptz,
  last_login_at timestamptz,
  role text not null check (role in ('owner', 'admin', 'warehouse', 'dispatch', 'viewer')),
  can_view_cost boolean not null default false,
  can_manage_users boolean not null default false,
  active boolean not null default false,
  system_account boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_sessions_v2 (
  id text primary key,
  user_id bigint not null references public.app_users_v2(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists app_sessions_expires_idx on public.app_sessions_v2(expires_at);

