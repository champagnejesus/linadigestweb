create or replace function public.register_inventory_movement(
  p_product_id bigint,
  p_type text,
  p_quantity integer,
  p_reason text,
  p_lot text,
  p_expiration_date date,
  p_note text,
  p_user_id text,
  p_user_name text
)
returns table(new_stock integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_stock integer;
  v_delta integer;
begin
  if p_type not in ('entry', 'output') or p_quantity < 1 then
    raise exception 'invalid_movement' using errcode = '22023';
  end if;

  select p.stock into v_stock
  from public.products p
  where p.id = p_product_id
  for update;

  if not found then
    raise exception 'product_not_found' using errcode = 'P0002';
  end if;

  v_delta := case when p_type = 'entry' then p_quantity else -p_quantity end;
  if v_stock + v_delta < 0 then
    raise exception 'insufficient_stock:%', v_stock using errcode = 'P0001';
  end if;

  update public.products
  set stock = stock + v_delta, updated_at = now()
  where id = p_product_id
  returning stock into new_stock;

  insert into public.movements
    (product_id, type, quantity, delta, reason, lot, expiration_date, note, source, user_id, user_name)
  values
    (p_product_id, p_type, p_quantity, v_delta, p_reason, p_lot, p_expiration_date, p_note, 'manual', p_user_id, p_user_name);

  return next;
end;
$$;

create or replace function public.scan_inventory_output(
  p_barcode text,
  p_scan_id text,
  p_user_id text,
  p_user_name text
)
returns table(status text, product_id bigint, product_name text, stock integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_product_id bigint;
  v_product_name text;
  v_stock integer;
  v_label_id bigint;
  v_label_used_at timestamptz;
begin
  select m.product_id into v_product_id
  from public.movements m
  where m.reference = p_scan_id;

  if found then
    select p.name, p.stock into v_product_name, v_stock
    from public.products p where p.id = v_product_id;
    status := 'duplicate'; product_id := v_product_id; product_name := v_product_name; stock := v_stock;
    return next; return;
  end if;

  if p_barcode ~* '^LD-[0-9]{3,18}$' then
    v_label_id := substring(p_barcode from 4)::bigint;
    select lp.product_id, lp.used_at into v_product_id, v_label_used_at
    from public.label_prints lp
    where lp.id = v_label_id
    for update;

    if not found then
      status := 'unknown_barcode'; product_id := null; product_name := null; stock := null;
      return next; return;
    end if;

    select p.name, p.stock into v_product_name, v_stock
    from public.products p
    where p.id = v_product_id
    for update;

    if v_label_used_at is not null then
      status := 'label_already_used'; product_id := v_product_id; product_name := v_product_name; stock := v_stock;
      return next; return;
    end if;
  else
    select p.id, p.name, p.stock into v_product_id, v_product_name, v_stock
    from public.products p
    where p.barcode = p_barcode
    for update;
  end if;

  if not found then
    status := 'unknown_barcode'; product_id := null; product_name := null; stock := null;
    return next; return;
  end if;
  if v_stock < 1 then
    status := 'out_of_stock'; product_id := v_product_id; product_name := v_product_name; stock := v_stock;
    return next; return;
  end if;

  begin
    insert into public.movements
      (product_id, type, quantity, delta, reason, note, source, reference, user_id, user_name)
    values
      (
        v_product_id,
        'output',
        1,
        -1,
        'Salida por escáner',
        case when v_label_id is null then 'Código ' else 'Código único ' end || p_barcode,
        'scanner',
        p_scan_id,
        p_user_id,
        p_user_name
      );
  exception when unique_violation then
    select p.stock into v_stock from public.products p where p.id = v_product_id;
    status := 'duplicate'; product_id := v_product_id; product_name := v_product_name; stock := v_stock;
    return next; return;
  end;

  if v_label_id is not null then
    update public.label_prints
    set used_at = now(), used_by_user_id = p_user_id, used_movement_reference = p_scan_id
    where id = v_label_id and used_at is null;

    if not found then
      status := 'label_already_used'; product_id := v_product_id; product_name := v_product_name; stock := v_stock;
      return next; return;
    end if;
  end if;

  update public.products
  set stock = stock - 1, updated_at = now()
  where id = v_product_id
  returning products.stock into v_stock;

  status := 'recorded'; product_id := v_product_id; product_name := v_product_name; stock := v_stock;
  return next;
end;
$$;

create or replace function public.undo_inventory_scan(
  p_scan_id text,
  p_user_id text,
  p_user_name text,
  p_can_manage boolean
)
returns table(status text, stock integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_movement_id bigint;
  v_product_id bigint;
  v_movement_user_id text;
  v_stock integer;
  v_undo_note text := 'Anulación de lectura ' || p_scan_id;
begin
  select m.id, m.product_id, m.user_id
  into v_movement_id, v_product_id, v_movement_user_id
  from public.movements m
  where m.reference = p_scan_id and m.source = 'scanner'
  for update;

  if not found then
    status := 'missing'; stock := null;
    return next; return;
  end if;

  if v_movement_user_id <> p_user_id and not p_can_manage then
    status := 'forbidden'; stock := null;
    return next; return;
  end if;

  perform 1
  from public.movements m
  where m.product_id = v_product_id and m.type = 'entry' and m.note = v_undo_note
  for update;

  if found then
    select p.stock into v_stock from public.products p where p.id = v_product_id;
    status := 'already_undone'; stock := v_stock;
    return next; return;
  end if;

  select p.stock into v_stock
  from public.products p
  where p.id = v_product_id
  for update;

  update public.products
  set stock = stock + 1, updated_at = now()
  where id = v_product_id
  returning products.stock into v_stock;

  insert into public.movements
    (product_id, type, quantity, delta, reason, note, source, user_id, user_name)
  values
    (v_product_id, 'entry', 1, 1, 'Anulación de salida por escáner', v_undo_note, 'manual', p_user_id, p_user_name);

  update public.label_prints
  set used_at = null, used_by_user_id = null, used_movement_reference = null
  where used_movement_reference = p_scan_id;

  status := 'undone'; stock := v_stock;
  return next;
end;
$$;

